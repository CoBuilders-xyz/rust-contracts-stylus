#!/usr/bin/env node
/**
 * Prepares copied example crates for standalone use with cargo-stylus.
 * 1. Copies Stylus.toml, rust-toolchain.toml, .cargo/config.toml into each example.
 * 2. Generates a workspace Cargo.toml at hardhat-examples/ so the copied crates
 *    can resolve their .workspace = true references without being in the parent workspace.
 */
import {
  cpSync,
  existsSync,
  mkdirSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { discoverExamples } from './hardhat-discover-examples.mjs';

const hardhatRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contractsDir = path.resolve(hardhatRoot, 'contracts');
const supportDir = path.resolve(hardhatRoot, 'hardhat-stylus');

if (!existsSync(contractsDir)) {
  console.error(
    'Missing hardhat-examples/contracts/. Run npm run prepare:hardhat or npm install here.',
  );
  process.exit(1);
}

const pairs = discoverExamples(contractsDir).filter((p) => p.packageName);

for (const { dir } of pairs) {
  cpSync(path.join(supportDir, 'Stylus.toml'), path.join(dir, 'Stylus.toml'));
  cpSync(
    path.join(supportDir, 'rust-toolchain.toml'),
    path.join(dir, 'rust-toolchain.toml'),
  );
  mkdirSync(path.join(dir, '.cargo'), { recursive: true });
  cpSync(
    path.join(supportDir, '.cargo', 'config.toml'),
    path.join(dir, '.cargo', 'config.toml'),
  );
}

// Generate workspace Cargo.toml so copied crates resolve .workspace = true
const members = pairs.map(({ dir }) =>
  path.relative(hardhatRoot, dir).replace(/\\/g, '/'),
);

const cargoToml = `# AUTO-GENERATED by hardhat-prepare-examples.mjs — do not edit manually.
[workspace]
members = [
${members.map((m) => `  "${m}",`).join('\n')}
]
resolver = "2"

[workspace.package]
authors = ["OpenZeppelin"]
edition = "2021"
license = "MIT"
repository = "https://github.com/OpenZeppelin/rust-contracts-stylus"
version = "0.3.0"

[workspace.dependencies]
# Path deps pointing to the parent repo source tree
openzeppelin-stylus = { path = "../contracts" }
openzeppelin-crypto = { path = "../lib/crypto" }
e2e = { path = "../lib/e2e" }

# Crates.io deps (pinned versions matching the parent workspace)
stylus-sdk = "=0.9.0"
alloy-primitives = { version = "=0.8.20", default-features = false, features = ["tiny-keccak"] }
alloy-sol-types = { version = "=0.8.20", default-features = false }
keccak-const = "0.2.0"
alloy = { version = "=0.7.3", features = [
  "contract",
  "network",
  "providers",
  "provider-http",
  "rpc-client",
  "json-rpc",
  "rpc-types-eth",
  "signer-local",
  "getrandom",
] }
eyre = "0.6.8"
tokio = { version = "1.12.0", features = ["full"] }
rand = "0.9.0"

[profile.release]
codegen-units = 1
panic = "abort"
opt-level = "z"
strip = true
lto = true
debug = false
rpath = false
debug-assertions = false
incremental = false

[profile.dev]
panic = "abort"
`;

writeFileSync(path.join(hardhatRoot, 'Cargo.toml'), cargoToml);

// cargo-stylus looks for Stylus.toml at the workspace root
cpSync(path.join(supportDir, 'Stylus.toml'), path.join(hardhatRoot, 'Stylus.toml'));

// .cargo/config.toml at workspace root (build-std, rustflags)
mkdirSync(path.join(hardhatRoot, '.cargo'), { recursive: true });
cpSync(
  path.join(supportDir, '.cargo', 'config.toml'),
  path.join(hardhatRoot, '.cargo', 'config.toml'),
);

console.log(`Hardhat: prepared ${pairs.length} examples (workspace Cargo.toml generated)`);
